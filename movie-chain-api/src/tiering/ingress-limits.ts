/**
 * Ingress-level limits, rendered FROM the same `tier` rows the application
 * guard reads (step 25): the edge refuses a flood before it costs a Node
 * process anything, and both layers agree on the numbers because they come
 * from one place. Regenerate on any tier or plan change: `pnpm ingress:limits`.
 *
 * Staff traffic arrives on <slug>.<base domain>, so the edge can key it per
 * tenant. A guest names its chain only through a screening id in the path,
 * which the edge cannot resolve — guest traffic is limited per address here,
 * and per tenant by the application guard.
 */
export interface IngressTier {
  code: string;
  rateLimitRps: number;
}
export interface IngressTenant {
  slug: string;
  tier: string;
  rateLimitRps: number | null; // negotiated override
}

const zone = (s: string) => `cinechain_${s.replace(/[^a-z0-9]/g, '_')}`;
/** Bursts absorb the first second of a spike; sustained traffic is held to the rate. */
const burstFor = (rps: number) => Math.max(10, rps);

export function renderIngressLimits(tiers: IngressTier[], tenants: IngressTenant[], baseDomain: string, perAddressRps: number): string {
  const domain = baseDomain.replace(/\./g, '\\.');
  const overridden = tenants.filter((t) => t.rateLimitRps !== null);
  const lines: string[] = [
    '# GENERATED by `pnpm ingress:limits` from the `tier` table and tenant plans. Do not edit by hand.',
    '# Include inside the nginx `http {}` block; apply the `limit_req` lines in the API `location`.',
    '',
    `map $host $cinechain_slug { ~^(?<slug>[a-z0-9-]+)\\.${domain}$ $slug; default ""; }`,
    '',
  ];
  // One zone per tier (keyed by slug, so each TENANT gets the tier's rate), and one per negotiated override.
  for (const t of tiers) {
    const members = tenants.filter((x) => x.tier === t.code && x.rateLimitRps === null);
    lines.push(`map $cinechain_slug $${zone(`tier_${t.code}`)}_key {`, ...members.map((m) => `  ${m.slug} ${m.slug};`), '  default "";', '}');
    lines.push(`limit_req_zone $${zone(`tier_${t.code}`)}_key zone=${zone(`tier_${t.code}`)}:10m rate=${t.rateLimitRps}r/s;`, '');
  }
  for (const t of overridden) {
    lines.push(`map $cinechain_slug $${zone(`tenant_${t.slug}`)}_key { ${t.slug} ${t.slug}; default ""; }`);
    lines.push(`limit_req_zone $${zone(`tenant_${t.slug}`)}_key zone=${zone(`tenant_${t.slug}`)}:1m rate=${t.rateLimitRps}r/s;`, '');
  }
  lines.push(`limit_req_zone $binary_remote_addr zone=cinechain_address:20m rate=${perAddressRps}r/s;`);
  lines.push('limit_req_status 429;', '');
  lines.push('# --- in the API location {} block:');
  for (const t of tiers) lines.push(`# limit_req zone=${zone(`tier_${t.code}`)} burst=${burstFor(t.rateLimitRps)} nodelay;`);
  for (const t of overridden) lines.push(`# limit_req zone=${zone(`tenant_${t.slug}`)} burst=${burstFor(t.rateLimitRps!)} nodelay;`);
  lines.push(`# limit_req zone=cinechain_address burst=${burstFor(perAddressRps)} nodelay;`);
  return lines.join('\n') + '\n';
}
